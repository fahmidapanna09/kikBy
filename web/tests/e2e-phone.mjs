import { BASE, check, launch, summary } from "./helpers.mjs";
const { browser, page, errors } = await launch();
await page.goto(`${BASE}/register`);
await page.getByLabel("Full name").fill("Phone Tester");
await page.getByLabel("Username").fill("phonetester");
await page.getByLabel("Email").fill("pt@example.com");
await page.getByLabel("Phone number (optional)").fill("abc");
await page.getByLabel("Password", { exact: true }).fill("Str0ng!Passw0rd");
await page.getByLabel("Confirm password").fill("Str0ng!Passw0rd");
await page.getByRole("button", { name: "Create account" }).click();
check("invalid phone rejected", await page.getByText("Use digits only, with an optional leading +").isVisible());
await page.getByLabel("Phone number (optional)").fill("+880 1712-345678");
await page.getByRole("button", { name: "Create account" }).click();
await page.waitForURL(`${BASE}/`);
check("register works with phone", true);
await page.goto(`${BASE}/settings/account`);
const v = await page.getByRole("textbox", { name: "Phone number" }).inputValue();
check("phone saved normalized", v === "+8801712345678", v);
await page.getByRole("textbox", { name: "Phone number" }).fill("12");
await page.getByRole("button", { name: "Save phone number" }).click();
check("short phone rejected in settings", await page.getByText(/valid phone number/).isVisible());
await page.getByRole("textbox", { name: "Phone number" }).fill("");
await page.getByRole("button", { name: "Save phone number" }).click();
await page.getByText("Phone number removed").waitFor();
check("phone removable", true);
check("no console errors", errors.length === 0, JSON.stringify(errors));
await browser.close(); summary();
