import { BASE, check, launch, loginDemo, summary } from "./helpers.mjs";
const S = process.env.SHOTS;
const { browser, page, errors } = await launch({ width: 1280, height: 860 });
await loginDemo(page);

console.log("Search");
await page.goto(`${BASE}/search`);
check("recent empty → helper state", await page.getByText("Find people").first().isVisible());
const box = page.getByLabel("Search people and chats");
await box.fill("a");
await page.waitForTimeout(500);
check("1 char does not search", await page.getByText("Type at least 2 characters").isVisible());
let calls = 0;
await box.fill("sa");
await box.type("k", { delay: 50 });
await page.getByText("Sakib Islam").first().waitFor();
check("people result shown (debounced)", true);
check("URL mirrors query", page.url().includes("q=sak"));
check("friend action on result", await page.getByRole("button", { name: /Remove Sakib|Message/ }).count() >= 0);
await box.fill("@zubair");
await page.getByText("Zubair Alam").first().waitFor();
check("@username search", true);
await page.getByRole("button", { name: "Add friend" }).click();
await page.getByText(/Friend request sent/).waitFor();
check("add friend from results", true);
await box.fill("qqqqq");
await page.getByText("No people found").waitFor();
check("no-results state", true);
await page.getByRole("tab", { name: /Chats/ }).click();
await box.fill("staging");
await page.getByRole("tab", { name: /Chats/ }).click();
await page.locator(".hl").first().waitFor();
check("chat results highlight matches", true);
await box.fill("");
await page.getByText("Recent searches").waitFor();
check("recent searches saved", await page.getByRole("button", { name: /zubair/ }).count() >= 1);
await page.getByRole("button", { name: /Remove .*zubair.* from recent/ }).click();
check("recent item removable", await page.getByRole("button", { name: /Remove .*zubair.* from recent/ }).count() === 0);
await page.getByRole("button", { name: "Clear all" }).click();
check("recent cleared", await page.getByText("Recent searches").count() === 0);
await page.evaluate(() => localStorage.setItem("kikbite.mock.fail", "1"));
await box.fill("rafi");
await page.getByRole("tab", { name: /People/ }).click();
await page.getByText("Couldn't load this").waitFor();
check("error state with retry", true);
await page.evaluate(() => localStorage.removeItem("kikbite.mock.fail"));
await page.getByRole("button", { name: "Try again" }).click();
await page.getByText("Rafi Khan").first().waitFor();
check("retry recovers", true);

console.log("Top bar search");
await page.getByRole("search").first().getByLabel("Search").fill("mim");
await page.getByRole("search").first().getByLabel("Search").press("Enter");
await page.getByText("Mim Chowdhury").first().waitFor();
check("top bar search routes to results", page.url().includes("/search?q=mim"));

console.log("Notifications");
await page.goto(`${BASE}/notifications`);
await page.getByText("Farhan Ali").first().waitFor();
check("shows unread dots", (await page.locator(".unread-dot").count()) === 3);
await page.getByRole("tab", { name: /Unread/ }).click();
check("unread filter", (await page.locator(".notif").count()) === 3);
if (S) await page.screenshot({ path: `${S}/notifications.png` });
await page.locator(".notif").first().click();
await page.waitForURL(/\/(friends|chats\/.*|profile\/.*)$/);
check("click navigates to target", true);
await page.goto(`${BASE}/notifications`);
await page.getByRole("button", { name: /Mark all as read/ }).click();
await page.getByText("All caught up").first().waitFor();
check("mark all read", (await page.locator(".unread-dot").count()) === 0);
check("badge cleared in sidebar", (await page.locator('.sidebar a[aria-label^="Notifications"]').getAttribute("aria-label")) === "Notifications");

console.log("Realtime notification arrives (mock server push ~20s)");
await page.goto(`${BASE}/`);
await page.waitForFunction(() => document.querySelector('.sidebar a[aria-label^="Notifications, "]'), null, { timeout: 40000 });
check("live notification badge appears without reload", true);

check("no console/page errors", errors.length === 0, JSON.stringify(errors));
await browser.close();
summary();
